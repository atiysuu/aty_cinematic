const tables = { en, tr }
let current = 'en'

export const t = (key, ...args) => {
  let s = (tables[current] && tables[current][key]) || en[key]
  if (s === undefined) return key
  args.forEach((a, i) => { s = s.replace('{' + i + '}', a) })
  return s
}

export const setLocale = (name) => { if (tables[name]) current = name }
